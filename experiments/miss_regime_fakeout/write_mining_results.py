"""Step 4 deliverable -- synthesizes results/mining_results.{json,txt} from the four
artifacts already produced this pass (phase0_attribution, phase1_build, candidates_report,
regime_cell_cross). Pure aggregation/formatting, no new compute. ASCII-only output.

This script does NOT apply the DESIGN.md A3 whole-pass kill criterion -- it reports the
mechanical ADVANCES/FAILS line per candidate (z>=3, N>=500, both interleaved-year halves,
arithmetic only) and leaves the pre-registered kill-criterion judgment to FABLE.
"""
from __future__ import annotations

import json
import os
import sys
import time

_HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS_DIR = os.path.join(_HERE, "results")

GATE_Z = 3.0
GATE_N = 500


def load(name):
    with open(os.path.join(RESULTS_DIR, name), encoding="ascii", errors="replace") as f:
        return json.load(f)


def clears(r):
    if r is None or r.get("skipped"):
        return False
    nn = r.get("n_treated") if r.get("n_treated") is not None else r.get("n", 0)
    return abs(r.get("t_clust", 0.0)) >= GATE_Z and nn >= GATE_N


def fmt_r(r, label):
    if r is None:
        return "%s: NOT RUN" % label
    if r.get("skipped"):
        return "%s: SKIPPED (N=%d < floor)" % (label, r.get("n", 0))
    nt = r.get("n_treated")
    ntxt = (" N_treated=%d" % nt) if nt is not None else ""
    return "%s: N=%d%s G=%d t_clust=%+.2f t_plain=%+.2f beta=%+.4f" % (
        label, r["n"], ntxt, r.get("n_clusters", 0), r["t_clust"], r["t_plain"], r["beta"])


def sign_summary(sign_tbl):
    if not sign_tbl:
        return "n/a"
    parts = []
    for yr in sorted(sign_tbl.keys(), key=lambda x: int(x)):
        v = sign_tbl[yr]
        if v.get("skipped"):
            parts.append("%s:skip" % yr)
        else:
            parts.append("%s%s" % (yr, v.get("sign", "?")))
    return " ".join(parts)


def candidate_block(key, cr, out_lines, cohort_def, primary=True):
    c = cr[key]
    p2 = c["phase2_full"]
    interl = c.get("phase4_interleaved", {})
    era = c.get("phase4_era_report_only", {})
    ortho_v = c.get("phase3_verdict", "not run")

    pooled_clears = clears(p2)
    even_clears = clears(interl.get("even"))
    odd_clears = clears(interl.get("odd"))
    mech_advances = pooled_clears and even_clears and odd_clears
    max_t = max([abs(x.get("t_clust", 0.0)) for x in
                 [p2, interl.get("even"), interl.get("odd")] if x and not x.get("skipped")], default=0.0)

    tag = "PRIMARY" if primary else "secondary/diagnostic (NOT part of A3 primary check)"
    out_lines.append("\n--- %s [%s] ---\n" % (key, tag))
    out_lines.append("cohort def: %s\n" % cohort_def)
    out_lines.append("  pooled:            %s\n" % fmt_r(p2, "FULL"))
    out_lines.append("  interleaved even:  %s\n" % fmt_r(interl.get("even"), "even"))
    out_lines.append("  interleaved odd:   %s\n" % fmt_r(interl.get("odd"), "odd"))
    out_lines.append("  era 2016-2021:     %s\n" % fmt_r(era.get("2016_2021"), "era_early"))
    out_lines.append("  era 2022-2026:     %s\n" % fmt_r(era.get("2022_2026"), "era_late"))
    out_lines.append("  era-robustness flag: %s\n" % c.get("era_robustness_flag", "n/a"))
    out_lines.append("  per-year sign table: %s\n" % sign_summary(c.get("phase4_sign_table", {})))
    out_lines.append("  orthogonality: %s\n" % ortho_v)
    out_lines.append("  max |t_clust| observed (pooled/even/odd): %.2f\n" % max_t)
    out_lines.append("  MECHANICAL ADVANCES/FAILS (z>=%.1f, N>=%d, BOTH halves -- arithmetic only): %s\n" %
                      (GATE_Z, GATE_N, "ADVANCES" if mech_advances else "FAILS"))

    return {
        "cohort_def": cohort_def, "primary": primary,
        "pooled": p2, "interleaved_even": interl.get("even"), "interleaved_odd": interl.get("odd"),
        "era_2016_2021": era.get("2016_2021"), "era_2022_2026": era.get("2022_2026"),
        "era_robustness_flag": c.get("era_robustness_flag"),
        "sign_table": c.get("phase4_sign_table"),
        "orthogonality_outcome": ortho_v,
        "max_t_clust_pooled_or_half": round(max_t, 3),
        "mechanical_advances_fails": "ADVANCES" if mech_advances else "FAILS",
    }


def main():
    t0 = time.time()
    p0 = load("phase0_attribution.json")
    p1 = load("phase1_build.json")
    cr = load("candidates_report.json")
    rc = load("regime_cell_cross.json")

    out_lines = []
    out_json = {"meta": {}}

    out_lines.append("=== miss_regime_fakeout Phases 2-4 MINING RESULTS (v%d) ===\n" % p1["version"])
    out_lines.append("generated by write_mining_results.py from candidates_report/phase0_attribution/phase1_build/regime_cell_cross\n")
    out_lines.append("GATE bar (DESIGN.md S5/A3, verbatim): cohort z>=3 (date-clustered) with N>=500 AND replication on a disjoint date-half\n")
    out_lines.append("This report applies the bar MECHANICALLY per candidate. It does NOT apply the DESIGN.md A3 whole-pass\n")
    out_lines.append("kill criterion -- that judgment belongs to FABLE, not this executor.\n\n")

    # ---- ledger stats ----
    out_lines.append("--- Ledger (Phase 1) ---\n")
    out_lines.append("version: v%d (%s)\n" % (p1["version"], p1["commit"]))
    out_lines.append("window: %s .. %s (holdout cutoff)\n" % (p1["window"][0], p1["window"][1]))
    out_lines.append("rows: population=%d  joined-with-barriers=%d  cols=43\n" % (p1["n_population"], p1["n_joined"]))
    out_lines.append("holdout guard: assert_no_holdout_leak PASSED in-build (queue task 582 run.log; max date <= cutoff)\n")
    out_lines.append("candidate coverage: c1_reversal=%d  c2_admission_zone=%d (spread_ok=%d)  c3_near_gate<=2=%d  c3_cross70=%d  c3_cross75=%d\n" %
                      (p1["n_c1_reversal"], p1["n_c2_admission_zone"], p1["n_c2_admission_zone_spread_ok"],
                       p1["n_c3_near_gate_leq2"], p1["n_c3_cross_70"], p1["n_c3_cross_75"]))
    out_lines.append("year range: %d-%d\n\n" % tuple(p1["year_range"]))
    out_json["meta"]["ledger"] = p1

    # ---- Phase 0 table ----
    out_lines.append("--- Phase 0: fakeout dominant-stage attribution (HOLDOUT-RESTRICTED, A1: <=2026-06-15, v69+) ---\n")
    out_lines.append("window: intraday-log date <= %s, versions %s\n" % (p0.get("window_max_date"), p0.get("versions")))
    out_lines.append("fakeout def: %s\n" % p0.get("fakeout_def"))
    out_lines.append("N fakeout events = %d\n" % p0.get("n_events", "?"))
    out_json["phase0"] = p0
    out_lines.append("stage x version tally: %s\n" % json.dumps(p0.get("tally_stage_x_version", {})))
    out_lines.append("LIVE-mechanism ranking (retired-dampener excluded per A1): %s\n" % json.dumps(p0.get("live_mechanism_ranking", {})))
    out_lines.append("RETIRED-mechanism tally (cannot fire on v74): %s\n" % json.dumps(p0.get("retired_mechanism_tally", {})))
    out_lines.append("volume-stage transition pairs: %s\n" % json.dumps(p0.get("volume_transition_pairs", {})))
    out_lines.append("(full per-event table: results/phase0_attribution.txt)\n\n")

    # ---- A7 SPREAD_TILT overlap ----
    a7 = cr["a7_spread_tilt_overlap"]
    out_lines.append("--- A7: SPREAD_TILT / candidate-2 literal-overlap pre-check (mandatory, ran before c2 mining) ---\n")
    out_lines.append("N(SPREAD_TILT-tilted rows)=%d  N(c2 zone, spread known)=%d  N(intersection)=%d\n" %
                      (a7["n_tilted"], a7["n_zone"], a7["n_intersection"]))
    out_lines.append("overlap %% of tilted rows also in c2 zone = %.1f%%  |  overlap %% of c2 zone rows also tilted = %.1f%%\n" %
                      (a7["pct_tilted_rows_in_zone"], a7["pct_zone_rows_that_are_tilted"]))
    out_lines.append("VERDICT: %s (threshold >=50%% of tilted rows also in zone)\n\n" % a7["carve_out_verdict"])
    out_json["a7_spread_tilt_overlap"] = a7

    # ---- Candidates ----
    out_json["candidates"] = {}
    out_lines.append("=== CANDIDATES ===\n")

    out_json["candidates"]["candidate_1_reversal_volume_guard_CALLS"] = candidate_block(
        "candidate_1_reversal_volume_guard_CALLS", cr, out_lines,
        "treat=c1_is_reversal (volume_signal in {ABSORPTION,CLIMAX} AND volume_magnitude>0); "
        "population=CALLS (overall>=68), non-panic (VIX<28); outcome=exit_return (30dte_apex w=15); "
        "controls=[overall,sigma_pct]", primary=True)
    out_json["candidates"]["candidate_1_reversal_volume_guard_PUTS_secondary"] = candidate_block(
        "candidate_1_reversal_volume_guard_PUTS_secondary", cr, out_lines,
        "same treat as c1, population=PUTS instead of CALLS (design's own live evidence was calls-only; "
        "this is a diagnostic secondary, not a licensed primary test)", primary=False)
    cm = cr["candidate_1_continuous_magnitude_secondary"]
    out_lines.append("\n--- candidate_1 continuous reversal-magnitude secondary (within reversal-only subset) ---\n")
    out_lines.append("  %s\n" % fmt_r(cm, "magnitude"))
    out_json["candidates"]["candidate_1_continuous_magnitude_secondary"] = cm

    out_json["candidates"]["candidate_2_admission_boundary_spread_CARVED"] = candidate_block(
        "candidate_2_admission_boundary_spread_CARVED", cr, out_lines,
        "treat=c2_spread (continuous SPREAD_TILT-formula component-disagreement metric on "
        "[trend,bb,rsi,macd,stoch]); population=CALLS admission zone [68,77], non-panic, "
        "SPREAD_TILT-tilted region (75-79 & spread>26.9) EXCLUDED per A7 carve-out; "
        "outcome=exit_return; controls=[overall,sigma_pct]", primary=True)
    out_json["candidates"]["candidate_2_admission_boundary_spread_FULLZONE_fyi"] = candidate_block(
        "candidate_2_admission_boundary_spread_FULLZONE_fyi", cr, out_lines,
        "same as c2 CARVED but WITHOUT the A7 carve-out (FYI only, not gate-qualifying)", primary=False)

    out_json["candidates"]["candidate_3_regime_boundary_crossing_CALLS"] = candidate_block(
        "candidate_3_regime_boundary_crossing_CALLS", cr, out_lines,
        "treat=c3_near_gate_flag (min(|pre_regime-70|,|pre_regime-75|)<=2); population=CALLS, "
        "non-panic, pre_regime known; outcome=exit_return; controls=[overall,sigma_pct]", primary=True)
    for sub_key, sub_label in [("candidate_3_continuous_distance_secondary", "continuous near_gate_dist"),
                                ("candidate_3_c3_cross_70_secondary", "c3_cross_70 flag"),
                                ("candidate_3_c3_cross_75_secondary", "c3_cross_75 flag")]:
        r = cr[sub_key]
        out_lines.append("\n--- candidate_3 %s secondary ---\n" % sub_label)
        out_lines.append("  %s\n" % fmt_r(r, sub_label))
        out_json["candidates"][sub_key] = r

    # ---- Regime-cell cross addendum ----
    out_lines.append("\n=== Phase 2 addendum: 12-cell regime cross (VIX band x McClellan sign), descriptive secondary axis ===\n")
    out_lines.append("(does NOT alter the pooled/interleaved-half ADVANCES bar; panic band empty by construction, commitment 4)\n")
    for cand_key in ["candidate_1_reversal_volume_guard_CALLS", "candidate_2_admission_boundary_spread_CARVED",
                     "candidate_3_regime_boundary_crossing_CALLS"]:
        cells = rc.get(cand_key, {})
        out_lines.append("\n%s:\n" % cand_key)
        max_cell_t, max_cell_label = 0.0, None
        for cell_key, r in cells.items():
            if r.get("skipped"):
                continue
            t = abs(r.get("t_clust", 0.0))
            if t > max_cell_t:
                max_cell_t, max_cell_label = t, cell_key
            out_lines.append("    [%s] N=%d t_clust=%+.2f\n" % (cell_key, r["n"], r["t_clust"]))
        out_lines.append("    max |t_clust| across cells: %.2f (%s) -- below z=3 gate in every cell\n" %
                          (max_cell_t, max_cell_label))
    out_json["regime_cell_cross"] = rc

    # ---- Summary table ----
    out_lines.append("\n=== SUMMARY: mechanical bar outcomes (z>=%.1f, N>=%d, BOTH interleaved-year halves) ===\n" % (GATE_Z, GATE_N))
    primary_keys = ["candidate_1_reversal_volume_guard_CALLS",
                    "candidate_2_admission_boundary_spread_CARVED",
                    "candidate_3_regime_boundary_crossing_CALLS"]
    all_max_t = []
    for k in primary_keys:
        blk = out_json["candidates"][k]
        out_lines.append("%-48s : %-8s (pooled t_clust=%+.2f, max pooled/half |t_clust|=%.2f)\n" %
                          (k, blk["mechanical_advances_fails"], blk["pooled"]["t_clust"], blk["max_t_clust_pooled_or_half"]))
        all_max_t.append(blk["max_t_clust_pooled_or_half"])
    # global max across every test run this pass (primary + secondary + continuous)
    global_max = 0.0
    global_label = None
    for k, blk in out_json["candidates"].items():
        if not isinstance(blk, dict):
            continue
        if "max_t_clust_pooled_or_half" in blk:
            if blk["max_t_clust_pooled_or_half"] > global_max:
                global_max, global_label = blk["max_t_clust_pooled_or_half"], k
        elif "t_clust" in blk and not blk.get("skipped"):
            if abs(blk["t_clust"]) > global_max:
                global_max, global_label = abs(blk["t_clust"]), k
    out_lines.append("\nAcross ALL primary + secondary + continuous clustered-OLS tests run this pass, the single largest\n")
    out_lines.append("|t_clust| observed was %.2f (%s). No test -- primary, secondary, pooled, or any\n" % (global_max, global_label))
    out_lines.append("individual interleaved half or regime cell -- reached the pre-registered z>=3 bar.\n")
    out_lines.append("\nThis is the arithmetic result of the mechanical bar. Applying the DESIGN.md A3 whole-pass kill\n")
    out_lines.append("criterion to this result is FABLE's call, not this executor's.\n")

    out_json["meta"]["summary"] = {
        "primary_verdicts": {k: out_json["candidates"][k]["mechanical_advances_fails"] for k in primary_keys},
        "global_max_abs_t_clust": global_max,
        "global_max_label": global_label,
        "gate_z": GATE_Z, "gate_n": GATE_N,
    }

    elapsed = time.time() - t0
    out_lines.append("\n=== DONE in %.2fs ===\n" % elapsed)
    out_json["meta"]["elapsed_s"] = round(elapsed, 2)

    out_txt = os.path.join(RESULTS_DIR, "mining_results.txt")
    out_json_path = os.path.join(RESULTS_DIR, "mining_results.json")
    with open(out_txt, "w", encoding="ascii", errors="replace") as f:
        f.writelines(out_lines)
    with open(out_json_path, "w", encoding="ascii") as f:
        json.dump(out_json, f, indent=2, default=str)
    print("wrote %s" % out_txt)
    print("wrote %s" % out_json_path)
    print("=== DONE in %.2fs ===" % elapsed)


if __name__ == "__main__":
    main()
